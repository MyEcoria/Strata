"""tools/flint/kv_codebooks.py - trains the codebooks of the trellis KV cache (src/flint/flint_kv_codebooks.h).

    python tools/flint/kv_codebooks.py --out src/flint/flint_kv_codebooks.h

The trellis (bit-shift, 8 state bits, k = 2, 3 or 4 bits per sample) keeps a table of 256 values, one per state.  A vector of 128
samples is first rotated (random signs, then a Hadamard transform) and divided by its RMS, so its samples are close to N(0, 1);
the Viterbi search then picks the path whose table values are closest.  The table is trained the way a Lloyd quantiser is:
encode N(0, 1) vectors, move each value to the mean of the samples that chose it, and repeat.  numpy only; a few minutes.
"""
import argparse
import numpy as np

D, L = 128, 8


def hash_cb(L):
    """The starting table: QTIP's "1MAD" computed code (an LCG, then the sum of the four bytes), scaled to unit variance."""
    s = np.arange(1 << L, dtype=np.uint64)
    v = (np.uint64(34038481) * s + np.uint64(76625530)) & np.uint64(0xFFFFFFFF)
    by = [(v >> np.uint64(8 * i)) & np.uint64(255) for i in range(4)]
    cb = ((by[0] + by[1] + by[2] + by[3]).astype(np.float64) - 510.0) / 147.8
    return cb / np.sqrt(np.mean(cb ** 2))


def viterbi(x, cb, k):
    """x (N, D) -> the state of every sample on the best path (N, D).  The path starts in state 0."""
    N, T = x.shape
    S = 1 << L
    cost = np.full((N, S), 1e30)
    cost[:, 0] = 0.0
    back = np.zeros((T, N, S), dtype=np.uint8)
    sp = np.arange(S)
    pred = [((sp >> k) | (j << (L - k))) for j in range(1 << k)]
    for i in range(T):
        e = (x[:, i:i + 1] - cb[None, :]) ** 2
        cand = np.stack([cost[:, p] for p in pred], 0)
        j = np.argmin(cand, 0)
        back[i] = j
        cost = np.take_along_axis(cand, j[None], 0)[0] + e
    s = np.argmin(cost, 1)
    st = np.zeros((N, T), dtype=np.int64)
    for i in range(T - 1, -1, -1):
        st[:, i] = s
        j = back[i][np.arange(N), s].astype(np.int64)
        s = (s >> k) | (j << (L - k))
    return st


def snr(x, y):
    return 10 * np.log10(np.mean(x * x) / np.mean((x - y) ** 2))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--rounds", type=int, default=30)
    ap.add_argument("--vectors", type=int, default=600)
    a = ap.parse_args()
    rng = np.random.default_rng(20261101)
    test = rng.standard_normal((500, D))
    out = ["// Generated by tools/flint/kv_codebooks.py - the 256-entry tables of the trellis KV cache (do not edit).",
           "#pragma once", ""]
    for k in (2, 3, 4):
        cb = hash_cb(L)
        for r in range(a.rounds):
            x = rng.standard_normal((a.vectors, D))
            st = viterbi(x, cb, k)
            num = np.bincount(st.ravel(), weights=x.ravel(), minlength=1 << L)
            den = np.bincount(st.ravel(), minlength=1 << L)
            cb = np.where(den > 0, num / np.maximum(den, 1), cb)
        d = snr(test, cb[viterbi(test, cb, k)])
        print(f"k={k}: {d:.2f} dB on 500 fresh N(0,1) vectors (Shannon {6.02 * k:.2f})", flush=True)
        out.append(f"// k = {k} bits per sample: {d:.2f} dB on N(0, 1) (the bound is {6.02 * k:.2f})")
        out.append(f"__device__ const float kKvTrellis{k}[256] = {{")
        for i in range(0, 256, 8):
            out.append("    " + ", ".join(f"{v:.6f}f" for v in cb[i:i + 8]) + ",")
        out.append("};")
        out.append("")
    open(a.out, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
